// Data store.
//
// Two modes, same API for the rest of the code (db.data, db.read(), db.write()):
//
//  * DATABASE_URL set  -> PostgreSQL (Supabase). Every record of every
//    collection is one JSONB row in the table `praman_records`. The whole
//    data set is loaded into memory at start-up, and each db.write() saves
//    only the records that changed (insert / update / delete) in one
//    transaction. This needs ONE server instance (Render: keep instances = 1),
//    because the in-memory copy is the working copy.
//
//  * no DATABASE_URL   -> local JSON file data/db.json (development only;
//    on Render this file is wiped on every deploy/restart).
const path = require('path');
const fs = require('fs');

const defaultData = () => ({
  users: [],
  whatsappAccounts: [],
  phoneOtps: [],
  cases: [],
  evidence: [],
  custody: [],
  callSessions: [],
  transcripts: [],
  reports: [],
  webhookDeliveries: [], // events waiting to be / already sent to a vendor's system
  errorLog: [],          // recent server problems (Super Admin → System health)
  notifications: [],     // in-app notifications for a firm's team
  auditLog: [],          // who did what (logins, settings, sign-offs, exports)
  dataRequests: [],      // customers asking for their data to be deleted
  backupLog: [],         // automatic backups saved to file storage
  invoices: [],          // bills to vendor firms (draft / issued / paid / void) with their payments
  wallets: {},           // prepaid wallet balance per firm: { vendorId: { balance } }
  walletTxns: [],        // wallet ledger: top-ups, report and ID-check charges, refunds
  billingSettings: {},   // Praman's own invoice details: legal name, GSTIN, bank, UPI, numbering
  aiUsage: {},           // Gemini calls per day: { 'YYYY-MM-DD': { text, tts, errors, ... } }
  demoRequests: [],      // 'Request a demo' form of the website (Super Admin sees them)
  fileFacts: [],         // exact fingerprint + PDF / photo metadata of every stored file (file-facts.js)
  platformSettings: {} // Super Admin managed: geminiApiKey, gridlinesApiKey, R2, TURN ...
});

const dataDir = process.env.PRAMAN_DATA_DIR || path.join(__dirname, '..', 'data');
const jsonFile = path.join(dataDir, 'db.json');
const TABLE = (process.env.PRAMAN_TABLE || 'praman_records').replace(/[^a-z0-9_]/gi, '');
const SEP = '\u0000';

// ---------------------------------------------------------------- Postgres
class PgStore {
  constructor(url) {
    const { Pool } = require('pg');
    const local = /@(localhost|127\.0\.0\.1)[:/]/.test(url) || /sslmode=disable/.test(url);
    this.pool = new Pool({
      connectionString: url,
      ssl: local ? false : { rejectUnauthorized: false },
      max: 4,
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 15_000
    });
    this.pool.on('error', e => console.error('Postgres pool error:', e.message));
    this.snap = new Map(); // "collection\0id" -> JSON text last saved
  }

  async ensureTable() {
    await this.pool.query(`
      create table if not exists ${TABLE} (
        collection text not null,
        id         text not null,
        data       jsonb not null,
        updated_at timestamptz not null default now(),
        seq        bigint generated by default as identity,
        primary key (collection, id)
      )`);
    await this.pool.query(`alter table ${TABLE} add column if not exists seq bigint generated by default as identity`);
    // On Supabase, keep the table away from the public API keys.
    await this.pool.query(`alter table ${TABLE} enable row level security`).catch(() => {});
  }

  async load() {
    const { rows } = await this.pool.query(`select collection, id, data from ${TABLE} order by collection, seq`);
    const data = {};
    for (const r of rows) {
      this.snap.set(r.collection + SEP + r.id, JSON.stringify(r.data));
      if (r.id === '_' && !Array.isArray(data[r.collection])) data[r.collection] = r.data; // object collections
      else (data[r.collection] ||= []).push(r.data);
    }
    return { data, count: rows.length };
  }

  // Turns db.data into rows: key -> JSON text.
  static rows(data) {
    const out = new Map();
    for (const [col, val] of Object.entries(data || {})) {
      if (Array.isArray(val)) {
        const used = new Set();
        val.forEach((rec, i) => {
          if (rec == null) return;
          let id = String(rec.id ?? rec.caseId ?? `idx_${i}`);
          if (used.has(id)) { let n = 2; while (used.has(`${id}#${n}`)) n++; id = `${id}#${n}`; }
          used.add(id);
          out.set(col + SEP + id, JSON.stringify(rec));
        });
      } else if (val && typeof val === 'object') {
        out.set(col + SEP + '_', JSON.stringify(val));
      }
    }
    return out;
  }

  async flush(data) {
    const now = PgStore.rows(data);
    const up = [], del = [];
    for (const [k, json] of now) if (this.snap.get(k) !== json) up.push([k, json]);
    for (const k of this.snap.keys()) if (!now.has(k)) del.push(k);
    if (!up.length && !del.length) return { upserted: 0, deleted: 0 };

    const client = await this.pool.connect();
    try {
      await client.query('begin');
      for (let i = 0; i < up.length; i += 500) {
        const part = up.slice(i, i + 500);
        const cols = part.map(([k]) => k.split(SEP)[0]);
        const ids = part.map(([k]) => k.split(SEP)[1]);
        const docs = part.map(([, j]) => j);
        await client.query(
          `insert into ${TABLE} (collection, id, data, updated_at)
             select c, i, d::jsonb, now() from unnest($1::text[], $2::text[], $3::text[]) with ordinality as t(c, i, d, n) order by n
           on conflict (collection, id) do update set data = excluded.data, updated_at = now()`,
          [cols, ids, docs]);
      }
      for (let i = 0; i < del.length; i += 1000) {
        const part = del.slice(i, i + 1000);
        await client.query(
          `delete from ${TABLE} t using unnest($1::text[], $2::text[]) as d(c, i) where t.collection = d.c and t.id = d.i`,
          [part.map(k => k.split(SEP)[0]), part.map(k => k.split(SEP)[1])]);
      }
      await client.query('commit');
    } catch (e) {
      await client.query('rollback').catch(() => {});
      throw e;
    } finally {
      client.release();
    }
    for (const [k, json] of up) this.snap.set(k, json);
    for (const k of del) this.snap.delete(k);
    return { upserted: up.length, deleted: del.length };
  }
}

class PgDb {
  constructor(url) {
    this.store = new PgStore(url);
    this.data = defaultData();
    this.queued = null;
    this.running = null;
    this.retryTimer = null;
    this.lastWriteError = null;
    this.lastWriteAt = null;
    this.mode = 'postgres';
  }
  async read() { /* the in-memory copy is the working copy */ }
  // Saves changed records. Calls made while a save is running are merged
  // into one follow-up save, so a burst of writes costs at most two saves.
  write() {
    if (this.queued) return this.queued;
    const before = this.running ? this.running.catch(() => {}) : Promise.resolve();
    this.queued = before.then(() => {
      this.queued = null;
      this.running = this.store.flush(this.data)
        .then(r => { this.lastWriteError = null; this.lastWriteAt = new Date().toISOString(); try { require('./services/mirror').schedule(this); } catch { /* optional */ } return r; })
        .catch(e => {
          // Keep the change in memory and try again shortly, so a short
          // database hiccup does not lose anything.
          this.lastWriteError = { message: e.message, at: new Date().toISOString() };
          console.error('Database save failed (will retry in 5 s):', e.message);
          if (!this.retryTimer) this.retryTimer = setTimeout(() => { this.retryTimer = null; this.write().catch(() => {}); }, 5000);
          throw e;
        })
        .finally(() => { this.running = null; });
      return this.running;
    });
    return this.queued;
  }
}

// ---------------------------------------------------------------- JSON file
function makeFileDb() {
  const { Low } = require('lowdb');
  const { JSONFile } = require('lowdb/node');
  if (!fs.existsSync(dataDir)) fs.mkdirSync(dataDir, { recursive: true });
  const low = new Low(new JSONFile(jsonFile), defaultData());
  low.mode = 'file';
  return low;
}

const db = process.env.DATABASE_URL ? new PgDb(process.env.DATABASE_URL) : makeFileDb();

// Before every save: each evidence item carries its firm (vendorId) and must
// point to a case that exists (or be explicitly 'unassigned' to a firm).
const _write = db.write.bind(db);
db.write = function () {
  const d = this.data;
  if (d && Array.isArray(d.evidence) && Array.isArray(d.cases)) {
    let byId = null;
    for (const e of d.evidence) {
      if (e && e.caseId && !e.vendorId) {
        byId = byId || new Map(d.cases.map(c => [c.id, c]));
        const c = byId.get(e.caseId);
        if (c) e.vendorId = c.vendorId;
      }
    }
  }
  return _write();
};

function fillDefaults(data) {
  const d = data || {};
  const def = defaultData();
  for (const k of Object.keys(def)) if (d[k] == null) d[k] = def[k];
  return d;
}

async function init() {
  if (db.mode === 'postgres') {
    await db.store.ensureTable();
    const { data, count } = await db.store.load();
    db.data = fillDefaults(data);
    // First start on an empty database: bring over data/db.json if it has anything.
    if (count === 0 && fs.existsSync(jsonFile)) {
      try {
        const old = JSON.parse(fs.readFileSync(jsonFile, 'utf8'));
        const has = Object.values(old || {}).some(v => (Array.isArray(v) ? v.length : v && Object.keys(v).length));
        if (has) {
          db.data = fillDefaults(old);
          const r = await db.write();
          console.log(`Database: imported data/db.json into Postgres (${r.upserted} records).`);
        }
      } catch (e) { console.warn('Database: could not import data/db.json —', e.message); }
    }
    const fixed = backfill(db.data);
    if (fixed) { await db.write(); console.log(`Database: updated ${fixed} older record(s) (case numbers, links).`); }
    const n = Object.values(db.data).reduce((s, v) => s + (Array.isArray(v) ? v.length : 0), 0);
    console.log(`Database: PostgreSQL (${TABLE}), ${n} records loaded.`);
  } else {
    await db.read();
    db.data = fillDefaults(db.data);
    backfill(db.data);
    await db.write();
    console.warn('Database: local file data/db.json — set DATABASE_URL to use PostgreSQL (data in this file is lost on every Render deploy).');
  }
  // Save anything pending when Render stops the server.
  for (const sig of ['SIGTERM', 'SIGINT']) {
    process.once(sig, async () => {
      try { await db.write(); } catch (e) { console.error('Final save failed:', e.message); }
      process.exit(0);
    });
  }
}

const { uid, backfill } = require('./services/ids');

module.exports = { db, init, uid };
